/**
 * Converts the upstream gettext catalogs (locales/*.po, copied from ytmusicapi/locales) into
 * src/i18n/locales.ts so translations are bundled with the code and need no runtime file access.
 *
 * Usage: node scripts/po-to-ts.ts
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";

const root = join(import.meta.dirname, "..");
const localeDir = join(root, "locales");
const outFile = join(root, "src", "i18n", "locales.ts");

/** Minimal .po parser: handles msgid/msgstr pairs with multi-line string continuations. */
export function parsePo(source: string): Record<string, string> {
  const entries: Record<string, string> = {};
  let current: "msgid" | "msgstr" | null = null;
  let msgid = "";
  let msgstr = "";

  const flush = () => {
    // gettext falls back to the msgid when msgstr is empty, so empty translations are omitted
    if (msgid !== "" && msgstr !== "") entries[msgid] = msgstr;
    msgid = "";
    msgstr = "";
    current = null;
  };

  for (const rawLine of source.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (line === "" || line.startsWith("#")) {
      if (current === "msgstr") flush();
      continue;
    }
    const match = /^(msgid|msgstr)\s+(".*")$/.exec(line);
    if (match) {
      if (match[1] === "msgid" && current === "msgstr") flush();
      current = match[1] as "msgid" | "msgstr";
      const value = JSON.parse(match[2]!) as string;
      if (current === "msgid") msgid = value;
      else msgstr = value;
    } else if (line.startsWith('"') && current) {
      const value = JSON.parse(line) as string;
      if (current === "msgid") msgid += value;
      else msgstr += value;
    }
  }
  if (current === "msgstr") flush();
  return entries;
}

const catalogs: Record<string, Record<string, string>> = {};
for (const file of readdirSync(localeDir).filter((f) => f.endsWith(".po")).sort()) {
  catalogs[basename(file, ".po")] = parsePo(readFileSync(join(localeDir, file), "utf8"));
}

const output = `// GENERATED by scripts/po-to-ts.ts from locales/*.po — do not edit by hand.
// Source: https://github.com/sigma67/ytmusicapi/tree/main/ytmusicapi/locales (MIT)

export const LOCALES: Readonly<Record<string, Readonly<Record<string, string>>>> = ${JSON.stringify(catalogs, null, 2)};
`;
writeFileSync(outFile, output);
console.log(`Wrote ${Object.keys(catalogs).length} locales to ${outFile}`);
